const LOCALES = { en: "en-US", pt: "pt-BR" };
const STORAGE_KEY = "psmm-lang";

let current = "en";

export function detectLang() {
  let saved = null;
  try { saved = localStorage.getItem(STORAGE_KEY); } catch { /* no storage */ }
  if (saved && saved in STRINGS) return saved;
  const prefs = navigator.languages?.length ? navigator.languages : [navigator.language || "en"];
  return prefs.some((l) => String(l).toLowerCase().startsWith("pt")) ? "pt" : "en";
}

export function setLang(lang, persist = false) {
  current = lang in STRINGS ? lang : "en";
  document.documentElement.lang = LOCALES[current];
  if (persist) {
    try { localStorage.setItem(STORAGE_KEY, current); } catch { /* no storage */ }
  }
  return current;
}

export const getLang = () => current;
export const locale = () => LOCALES[current];

export function t(key, params) {
  let s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
  return s;
}

/** Applies data-i18n / -html / -title / -aria / -placeholder in ``root``. */
export function translateDom(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}

